/**
 * Emits SOURCE.md — the complete project documentation the task asks for:
 *   1. the file tree
 *   2. every file, verbatim
 *   3. the exact GitHub + Vercel commands
 *
 * Generated from the repository itself so it can never drift from the code.
 *   npm run docs
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', '.vercel', 'scripts', 'coverage']);
const SKIP_FILES = new Set(['SOURCE.md', 'package-lock.json']);
const BINARY = /\.(png|jpg|jpeg|gif|ico|woff2?|ttf|mp3|webm)$/i;

/** Files that make up the deliverable, in a logical reading order. */
function walk(dir, acc = []) {
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.')) continue;
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      if (SKIP_DIRS.has(name)) continue;
      walk(full, acc);
    } else if (!SKIP_FILES.has(name)) {
      acc.push(relative(ROOT, full));
    }
  }
  return acc;
}

const all = walk(ROOT);
const langOf = (file) => {
  if (file.endsWith('.tsx')) return 'tsx';
  if (file.endsWith('.ts')) return 'ts';
  if (file.endsWith('.css')) return 'css';
  if (file.endsWith('.json')) return 'json';
  if (file.endsWith('.html')) return 'html';
  if (file.endsWith('.md')) return 'md';
  if (file.endsWith('.svg')) return 'svg';
  if (file.endsWith('.mjs')) return 'js';
  return 'txt';
};

const ORDER = [
  /^README\.md$/,
  /^TESTING\.md$/,
  /^package\.json$/,
  /^index\.html$/,
  /^vite\.config\.ts$/,
  /^vercel\.json$/,
  /^tsconfig\.json$/,
  /^\.gitignore$/,
  /^api\//,
  /^scripts\//,
  /^public\//,
  /^src\/main\.tsx$/,
  /^src\/App\.tsx$/,
  /^src\/vite-env\.d\.ts$/,
  /^src\/styles\//,
  /^src\/os\//,
  /^src\/components\//,
  /^src\/hooks\//,
  /^src\/assets\//,
  /^src\/apps\//,
];
const files = [...all].sort((a, b) => {
  const rank = (f) => {
    const i = ORDER.findIndex((re) => re.test(f));
    return i === -1 ? ORDER.length : i;
  };
  const d = rank(a) - rank(b);
  return d !== 0 ? d : a.localeCompare(b);
});

/* ------------------------------ 1. file tree ----------------------------- */
const tree = ['owl/'];
const treeLines = new Set(files);
const dirs = new Set();
files.forEach((f) => {
  const parts = f.split('/');
  for (let i = 1; i < parts.length; i++) dirs.add(parts.slice(0, i).join('/'));
});
const sorted = [...dirs, ...files].sort();
const seenDirs = new Set();
for (const entry of sorted) {
  const depth = entry.split('/').length;
  const indent = '│   '.repeat(depth - 1);
  if (dirs.has(entry)) {
    if (seenDirs.has(entry)) continue;
    seenDirs.add(entry);
    const name = entry.split('/').pop();
    tree.push(`${indent}├── ${name}/`);
  } else if (treeLines.has(entry)) {
    tree.push(`${indent}├── ${entry.split('/').pop()}`);
  }
}

/* ----------------------------- 2. file bodies ---------------------------- */
const sections = files.map((file) => {
  const abs = join(ROOT, file);
  if (BINARY.test(file)) {
    return `### \`${file}\`\n\n> Binary asset (icon PNG). Generated by \`npm run icons\` from \`public/owl-icon-*.svg\`; not inlined here.\n`;
  }
  const body = readFileSync(abs, 'utf8');
  const stat = statSync(abs);
  return `### \`${file}\`\n\n_${stat.size} bytes · ${body.split('\n').length} lines_\n\n\`\`\`${langOf(file)}\n${body.replace(/\n$/, '')}\n\`\`\`\n`;
});

const totalBytes = files.reduce((n, f) => n + (BINARY.test(f) ? 0 : statSync(join(ROOT, f)).size), 0);
const totalLines = files.reduce((n, f) => n + (BINARY.test(f) ? 0 : readFileSync(join(ROOT, f), 'utf8').split('\n').length), 0);

const out = `# OWL — complete source

Generated by \`npm run docs\` (${new Date().toISOString().slice(0, 10)}).

- **${files.length} files**, ${totalLines.toLocaleString()} lines, ${(totalBytes / 1024).toFixed(0)} KB of source
- Branch: \`arena/4e88e37c-owl\` · repo: \`aamrabdelhay/owl\`
- Verified with \`npm run typecheck\`, \`npm run build\` and \`npm run smoke\` (boots the OS and opens
  every registered app in jsdom)

---

## 1. File tree

\`\`\`text
${tree.join('\n')}
\`\`\`

---

## 2. Every file

${sections.join('\n---\n\n')}
---

## 3. Publish it

### GitHub

The project is already committed on \`arena/4e88e37c-owl\`. To publish it yourself:

\`\`\`bash
cd owl
git checkout -b main 2>/dev/null || git checkout main   # if you want this on main
git add -A
git commit -m "OWL: retro QWERTY phone simulator"
git remote add origin https://github.com/aamrabdelhay/owl.git   # skip if it exists
git push -u origin HEAD
# then open a pull request:
gh pr create --fill --base main --head arena/4e88e37c-owl
\`\`\`

### Vercel

\`\`\`bash
npm i -g vercel
vercel login
vercel link                     # answer the prompts once
vercel --prod                   # build + deploy
\`\`\`

Dashboard route: **vercel.com → Add New → Project → Import Git Repository →
\`aamrabdelhay/owl\` → Deploy**. Vercel reads \`vercel.json\`: build \`npm run build\`,
output \`dist\`, SPA rewrite for everything except \`/api/*\`, and \`api/reader.ts\`
becomes a Node serverless function automatically. **No environment variables.**

Notes:

- The PWA service worker is generated at build time; the first visit caches the
  shell so later loads work offline.
- \`/api/reader\` is the only server-side code. Everything else is static.
- All user data lives in the visitor's browser (localStorage + IndexedDB), so
  there is no database or storage bucket to configure.
`;

writeFileSync(join(ROOT, 'SOURCE.md'), out);
console.log(`SOURCE.md: ${files.length} files, ${totalLines} lines, ${(out.length / 1024).toFixed(0)} KB`);
